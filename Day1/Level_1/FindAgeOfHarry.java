class FindAgeOfHarry {
	// Write a program to find the age of Harry
	public static void main(String[] args) {
		// Current year
		int currentYear = 2024;

		// Birth year of Harry
		int birthYear = 2000;

		// Current age of Harry
		int harryAge = (currentYear - birthYear);
		
		// Display harry age
		System.out.println("Harry's age in 2024 is " + harryAge);
	}
}